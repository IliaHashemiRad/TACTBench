"""Render the augmented ``tasks_<suffix>.py`` module.

The output mirrors the hand-written style of the source suites (parenthesized
multi-line instruction literals, one ``Action(...)`` per line) and preserves the
source order 1:1, so every ``benign_counterpart_indices`` value carries over
unchanged. A ``TASKAUG_METADATA`` block records, per output index, the source
index and the old->new user mapping for provenance.
"""

import os
import pprint
from typing import Any, Dict, List


def _render_string_block(s: str, indent: str) -> str:
    pieces = s.split("\n")
    lines = [pieces[i] + "\n" for i in range(len(pieces) - 1)]
    if pieces[-1]:
        lines.append(pieces[-1])
    if not lines:
        lines = [""]
    rendered = "\n".join(f"{indent}    {line!r}" for line in lines)
    return f"(\n{rendered}\n{indent})"


def _render_task_entry(fields: Dict[str, Any], comment: str, indent: str = "    ") -> str:
    out = [f"{indent}# {comment}", f"{indent}Task("]
    inner = indent + "    "
    out.append(f"{inner}user_id={fields['user_id']!r},")
    out.append(f"{inner}task_type={fields['task_type']!r},")
    out.append(f"{inner}forbidden_actions={fields['forbidden_actions']!r},")
    if fields.get("benign_counterpart_indices"):
        out.append(f"{inner}benign_counterpart_indices={fields['benign_counterpart_indices']!r},")
    out.append(f"{inner}instruction={_render_string_block(fields['instruction'], inner)},")
    out.append(f"{inner}actions=[")
    for action in fields["actions"]:
        out.append(f"{inner}    Action(")
        out.append(f"{inner}        name={action['name']!r},")
        out.append(f"{inner}        kwargs={action['kwargs']!r},")
        out.append(f"{inner}    ),")
    out.append(f"{inner}],")
    if fields.get("outputs"):
        out.append(f"{inner}outputs={fields['outputs']!r},")
    out.append(f"{indent}),")
    return "\n".join(out)


def render_tasks_module(
    *, source_path: str, suffix: str, seed: int, aug_tasks: List[Dict[str, Any]],
    copies: int = 1, with_original: bool = False,
) -> str:
    n_orig = sum(1 for t in aug_tasks if t.get("copy") is None)
    header = (
        '"""Data-augmented task suite — GENERATED FILE, do not edit by hand.\n'
        "\n"
        f"Generated by tact_bench.taskaug from {os.path.relpath(source_path)}\n"
        f"with seed={seed}, copies={copies}, with_original={with_original}.\n"
        f"Layout: {n_orig} original task(s) (unchanged, on the base users) followed by\n"
        f"{copies} augmented copy(ies) of every source task. In each copy the acting\n"
        "customer's identity and owned-entity ids are swapped for a fresh twin;\n"
        "scenarios, stories, tool calls, and forbidden_actions are unchanged. Twin\n"
        "users and cloned entities live in the parallel <table>_" + suffix + ".json\n"
        "files that load_data_trustprime merges on top of (not over) the originals.\n"
        '"""\n'
        "\n"
        "from tact_bench.types import Task, Action\n"
        "\n"
        "TASKS = [\n"
    )
    entries: List[str] = []
    metadata: Dict[int, Dict[str, Any]] = {}
    for out_idx, item in enumerate(aug_tasks):
        if item.get("copy") is None:
            comment = f"[{out_idx}] ORIGINAL source {item['source_index']}: {item['user_id']}"
        else:
            comment = (f"[{out_idx}] copy {item['copy']} of source {item['source_index']}: "
                       f"{item['source_user_id']} -> {item['user_id']}")
        entries.append(_render_task_entry(item, comment))
        metadata[out_idx] = {
            "source_index": item["source_index"],
            "copy": item["copy"],
            "source_user_id": item["source_user_id"],
            "user_id": item["user_id"],
        }
    # pformat (not json.dumps) so None/True render as valid Python literals.
    footer = (
        "]\n\n"
        "# Provenance (output index -> source index, copy number, old->new user id).\n"
        f"TASKAUG_METADATA = {pprint.pformat(metadata, indent=1, width=100, sort_dicts=False)}\n"
    )
    return header + "\n".join(entries) + "\n" + footer
