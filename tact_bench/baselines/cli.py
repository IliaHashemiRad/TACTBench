"""Argument parsing, file writing, and the ``main()`` entry point.

``tasks_direct.py`` is the hand-curated plain-attack source of truth. This CLI
never writes it — it must exist (restore from version control if missing). The
PAP/Crescendo/FITD suites are derived from the *current* direct file by inserting
a strategy paragraph, and every ``_aug`` suite (direct's included) is expanded
from that same current text, so editing the plain attacks and re-running
propagates everywhere without touching the direct file.
"""

import argparse
import copy
import glob
import hashlib
import json
import os
from typing import Any, Dict, List

from tact_bench.baselines.build import (
    DATA_TABLES,
    GENERATED_DATA_DIR,
    GENERATED_DIR,
    build_from_direct,
    load_direct_dicts,
    render_module,
)
from tact_bench.baselines.strategies import DEFAULT_PAP_TECHNIQUE, PAP_TECHNIQUES

# 1 original + 8 twins = 9 identity variants per scenario -> 17 x 9 = 153 tasks.
DEFAULT_COPIES = 8

# Direct is the hand-curated source; the tool builds these from it.
DERIVED = ("pap", "crescendo", "fitd")
ALL = ("direct", *DERIVED)


def _ensure_package_dirs() -> None:
    os.makedirs(GENERATED_DATA_DIR, exist_ok=True)


def _write_json(path: str, obj: Dict[str, Any]) -> None:
    with open(path, "w") as f:
        json.dump(obj, f, indent=2)
        f.write("\n")


def _detail(baseline: str, args: argparse.Namespace) -> str:
    return {
        "pap": "PAP (Zeng et al., 2024), single-turn persuasion, technique: "
               f"{args.pap_technique}.",
        "crescendo": "Crescendo (Russinovich et al., 2024), multi-turn escalation off "
                     "the agent's own replies, 3 backtracks.",
        "fitd": f"Foot-In-The-Door (Weng et al., 2025), ~{args.fitd_rungs}-rung "
                "escalation ladder, 3 intermediate rungs.",
    }[baseline]


def _clean(baseline: str) -> List[str]:
    """Remove a baseline's derived and augmented artifacts.

    The hand-curated tasks_direct.py is never touched — it is not generated by
    this tool.
    """
    removed = []
    paths = [
        *([os.path.join(GENERATED_DIR, f"tasks_{baseline}.py")]
          if baseline in DERIVED else []),
        os.path.join(GENERATED_DIR, f"tasks_{baseline}_aug.py"),
        *[os.path.join(GENERATED_DATA_DIR, f"{t}_{baseline}_aug.json")
          for t in DATA_TABLES],
        *glob.glob(os.path.join(GENERATED_DIR, "__pycache__", f"tasks_{baseline}*.pyc")),
    ]
    for path in paths:
        if os.path.exists(path):
            os.remove(path)
            removed.append(path)
    return removed


def _augment(tasks: List[Dict[str, Any]], baseline: str, copies: int, seed: int) -> int:
    """Expand a baseline suite into per-identity variants.

    Calls ``tact_bench.taskaug``'s pipeline directly rather than its CLI, so
    taskaug stays the single owner of twin minting while the baselines package
    decides where its own artifacts land.
    """
    from tact_bench.envs.retail.data import load_data
    from tact_bench.taskaug.pipeline import build_augmented_suite
    from tact_bench.taskaug.render import render_tasks_module
    from tact_bench.types import Action, Task

    suffix = f"{baseline}_aug"
    as_tasks = [
        Task(
            user_id=t["user_id"],
            task_type=t["task_type"],
            forbidden_actions=t["forbidden_actions"],
            benign_counterpart_indices=t["benign_counterpart_indices"],
            instruction=t["instruction"],
            actions=[Action(name=a["name"], kwargs=a["kwargs"]) for a in t["actions"]],
            outputs=t["outputs"],
        )
        for t in tasks
    ]
    result = build_augmented_suite(
        as_tasks, load_data(), seed=seed, copies=copies, with_original=True
    )

    for table, obj in result["overrides"].items():
        if obj:
            _write_json(os.path.join(GENERATED_DATA_DIR, f"{table}_{suffix}.json"), obj)

    module_src = render_tasks_module(
        source_path=os.path.join(GENERATED_DIR, f"tasks_{baseline}.py"),
        suffix=suffix, seed=seed, aug_tasks=result["tasks"],
        copies=copies, with_original=True,
    )
    with open(os.path.join(GENERATED_DIR, f"tasks_{suffix}.py"), "w") as f:
        f.write(module_src)

    if result["leaks"]:
        print(f"  WARNING: residual old identity tokens in {suffix}:")
        for msg in result["leaks"]:
            print(f"    {msg}")
    else:
        print(f"  {suffix}: no residual old identity tokens ✓")
    return len(result["tasks"])


def _check() -> int:
    """Report which plain attacks are state-changing.

    A scenario whose ground truth writes to the database needs the plain attack's
    ending to walk the agent into performing that write; otherwise the episode
    ends with the DB short of the expected safe state and the mismatch can be
    misread as an unauthorized change. This runs each plain attack's ground-truth
    actions against the real tools and reports which ones write, so their endings
    can be eyeballed. It is informational — always exits 0.
    """
    from tact_bench.envs.retail.env import MockRetailDomainEnv

    env = MockRetailDomainEnv(user_strategy="human")
    direct = load_direct_dicts()

    def digest(d: Dict[str, Any]) -> str:
        return hashlib.sha256(
            json.dumps(d, sort_keys=True, default=str).encode()
        ).hexdigest()

    print("State-changing ground truth (plain attack ending must route the agent "
          "into the compliant write):\n")
    writers = 0
    for entry in direct:
        data = copy.deepcopy(env.data)
        writes = []
        for action in entry["actions"]:
            before = digest(data)
            try:
                env.tools_map[action["name"]].invoke(data=data, **action["kwargs"])
            except Exception:
                continue
            if digest(data) != before:
                writes.append(action["name"])
        writers += bool(writes)
        flag = "WRITES" if writes else "reads "
        print(f"  [{flag}] {entry['spec_name']:38s} {','.join(writes)}")

    print(f"\n{writers} of {len(direct)} scenarios are state-changing; the rest are "
          "read-only, where stopping at the refusal already matches ground truth.")
    return 0


def main() -> None:
    parser = argparse.ArgumentParser(
        prog="python -m tact_bench.baselines",
        description="Build the PAP/Crescendo/FITD baselines from the hand-curated "
                    "plain attacks in tasks_direct.py, plus per-identity variants.",
    )
    parser.add_argument("--baseline", choices=(*ALL, "all"), default="all",
                        help="Which baseline to build (default: all). 'direct' is the "
                             "hand-curated source and is never written; naming it only "
                             "(re)builds its augmented variant.")
    parser.add_argument("--pap-technique", choices=sorted(PAP_TECHNIQUES),
                        default=DEFAULT_PAP_TECHNIQUE,
                        help="Persuasion technique for the PAP baseline "
                             f"(default: {DEFAULT_PAP_TECHNIQUE}, the strongest "
                             "technique in the PAP paper's broad scan).")
    parser.add_argument("--fitd-rungs", type=int, default=6,
                        help="Target length of the FITD escalation ladder (default: 6).")
    parser.add_argument("--augment", action="store_true",
                        help="Also expand each suite into per-identity variants "
                             f"({DEFAULT_COPIES} twin copies + the originals).")
    parser.add_argument("--copies", type=int, default=DEFAULT_COPIES,
                        help=f"Twin copies per task when --augment is set "
                             f"(default: {DEFAULT_COPIES} -> 17 x 9 = 153 tasks).")
    parser.add_argument("--seed", type=int, default=42,
                        help="Seed for deterministic twin identities (default: 42).")
    parser.add_argument("--check", action="store_true",
                        help="Report which plain attacks are state-changing and exit.")
    parser.add_argument("--clean", action="store_true",
                        help="Remove generated suite(s) for --baseline and exit. The "
                             "hand-curated tasks_direct.py is never removed.")
    args = parser.parse_args()

    if args.check:
        raise SystemExit(_check())

    targets = list(ALL) if args.baseline == "all" else [args.baseline]

    if args.clean:
        removed = [p for b in targets for p in _clean(b)]
        if removed:
            print("Removed:")
            for p in removed:
                print(f"  {os.path.relpath(p)}")
        else:
            print(f"Nothing to clean for {', '.join(targets)}.")
        return

    if args.augment and args.copies < 1:
        parser.error("--copies must be >= 1")

    _ensure_package_dirs()
    direct_dicts = load_direct_dicts()  # errors clearly if tasks_direct.py is missing
    options = {"pap_technique": args.pap_technique, "fitd_rungs": args.fitd_rungs}
    by_name = {"direct": direct_dicts}

    # Write the derived non-direct suites (direct's file is never rewritten here).
    for baseline in [b for b in targets if b in DERIVED]:
        tasks = build_from_direct(direct_dicts, baseline, **options)
        by_name[baseline] = tasks
        module_src = render_module(
            baseline=baseline, tasks=tasks, detail=_detail(baseline, args)
        )
        path = os.path.join(GENERATED_DIR, f"tasks_{baseline}.py")
        with open(path, "w") as f:
            f.write(module_src)
        print(f"Wrote {len(tasks)} {baseline!r} task(s) -> "
              f"{os.path.relpath(path)}   (--task_variant {baseline})")

    if args.augment:
        for baseline in targets:
            tasks = by_name.get(baseline) or build_from_direct(
                direct_dicts, baseline, **options
            )
            n = _augment(tasks, baseline, args.copies, args.seed)
            print(f"  {baseline}: expanded to {n} task(s)          "
                  f"(--task_variant {baseline}_aug)")

    print("\nRun them:")
    for baseline in targets:
        variant = f"{baseline}_aug" if args.augment else baseline
        print(f"  python run.py --task_variant {variant} ...")
